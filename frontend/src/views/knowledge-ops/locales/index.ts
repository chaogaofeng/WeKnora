export const opsMessages = {
  'en-US': en,
  'zh-CN': { ...en, ...zh },
  'ja-JP': en,
  'ko-KR': en,
  'ru-RU': en,
}
export function useOpsText() {
  const { locale } = useI18n()
  // Unknown locales use the explicit English module fallback, without changing the global locale tree.
  const k = (key: string) =>
    (locale.value === 'zh-CN' ? zh[key] : en[key]) ||
    en[key] ||
    key ||
    (locale.value === 'zh-CN' ? zh.unknown : en.unknown)
  const label = (value?: string | null) => (value ? k(value) : k('unknown'))
  const labelVerdict = (value?: string | null) =>
    value === 'partial' ? k('verdict_partial') : label(value)
  const date = (value?: string | null) =>
    value ? new Date(value).toLocaleString(locale.value) : k('unknown')
  return { k, label, labelVerdict, date }
}
